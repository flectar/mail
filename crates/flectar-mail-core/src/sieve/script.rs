//! The Sieve script the app keeps on a server, for automatic replies (#239)
//! and rules (#238), and what it reads in scripts. The app's script is
//! generated from what the user set and carries the replies as data in a
//! comment, which the app reads back, so another device sees the same
//! replies. The rules a device wrote go in their own part, which a device
//! saving replies keeps as it found it. A check value tells when someone
//! changed the script elsewhere. Scripts the app didn't write are only read,
//! to find which extensions they use and which scripts they run.

use super::rules::Section;
use crate::models::AutoReply;
use chrono::{Local, Offset, TimeZone};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

/// The app's own script.
pub(crate) const NAME: &str = "flectar-mail";
const HEADER: &str = "# Generated by Flectar Mail. Changes made here are replaced.";
const CHECK: &str = "# Check: ";
const DATA: &str = "# Data: ";
/// The script format, in the check line.
const FORMAT: &str = "1";
/// How often a sender gets the reply again, as Gmail does.
const DAYS: u32 = 4;
/// Lines up the tests of `if allof (`.
const INDENT: &str = "          ";

/// The first and last lines of the rules' part.
pub(super) const RULES_START: &str = "# Rules";
pub(super) const RULES_END: &str = "# End of rules";

/// What the app wrote in its script, as JSON in a comment.
#[derive(Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase", default)]
struct Data {
    enabled: bool,
    subject: String,
    text: String,
    starts_at: Option<i64>,
    ends_at: Option<i64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    rules: Option<RulesData>,
}

/// What the script says of its rules.
#[derive(Serialize, Deserialize, Default)]
#[serde(default)]
struct RulesData {
    digest: String,
    needs: Vec<String>,
}

/// The app's script as found on a server.
#[derive(Debug, Default, PartialEq, Eq)]
pub(crate) struct Found {
    /// The replies it holds, as the app wrote them.
    pub(crate) reply: AutoReply,
    /// The rules it runs, as a device wrote them.
    pub(crate) rules: Option<Section>,
    /// The user's own script it runs after its rules.
    pub(crate) beside: Option<String>,
    /// Someone changed it since the app wrote it.
    pub(crate) edited: bool,
}

/// The extensions the app's script needs.
pub(crate) fn needs(reply: &AutoReply, beside: Option<&str>) -> Vec<&'static str> {
    let mut needed = Vec::new();
    if reply.enabled {
        needed.push("vacation");
        if reply.starts_at.is_some() || reply.ends_at.is_some() {
            needed.extend(["date", "relational"]);
        }
    }
    if beside.is_some() {
        needed.push("include");
    }
    needed
}

/// The app's script for `reply`, sent for mail that reaches any of
/// `addresses`, then `rules`, then the user's own script `beside`. Days
/// compare as dates in the zone the user is in. The reply comes first, so
/// the rules that file mail away, and end the run, don't keep it from
/// going out. The user's script comes last, so a message a rule files away
/// isn't filed twice, as filing doesn't end a run.
pub(crate) fn generate(
    reply: &AutoReply,
    addresses: &[String],
    rules: Option<&Section>,
    beside: Option<&str>,
) -> String {
    let data = serde_json::to_string(&Data {
        enabled: reply.enabled,
        subject: reply.subject.clone(),
        text: reply.text.clone(),
        starts_at: reply.starts_at,
        ends_at: reply.ends_at,
        rules: rules.map(|rules| RulesData {
            digest: rules.digest.clone(),
            needs: rules.needs.clone(),
        }),
    })
    .unwrap_or_default();
    let mut body = format!("{DATA}{data}\r\n");
    let mut needed = needs(reply, beside)
        .into_iter()
        .map(str::to_owned)
        .collect::<Vec<_>>();
    for extension in rules.iter().flat_map(|rules| &rules.needs) {
        if !needed.contains(extension) {
            needed.push(extension.clone());
        }
    }
    if !needed.is_empty() {
        body.push_str(&format!("require {};\r\n", list(&needed)));
    }
    if reply.enabled {
        let mut tests = Vec::new();
        for (at, comparison) in [(reply.starts_at, "ge"), (reply.ends_at, "le")] {
            if let Some((zone, day)) = at.and_then(day) {
                tests.push(format!(
                    "currentdate :zone {} :value {} \"date\" {}",
                    string(&zone),
                    string(comparison),
                    string(&day)
                ));
            }
        }
        // Lists, newsletters, no-reply senders and mail the server took for
        // spam get no reply. Servers skip most of these too. (`exists` with
        // a list would need every header.)
        let guard = [
            "exists \"List-Id\"",
            "exists \"List-Unsubscribe\"",
            "header :contains \"X-Spam-Flag\" \"YES\"",
            "address :matches [\"From\", \"Sender\"] [\"noreply@*\", \"no-reply@*\"]",
        ];
        tests.push(format!(
            "not anyof ({})",
            guard.join(&format!(",\r\n{INDENT}           "))
        ));
        let mut action = format!("vacation :days {DAYS}");
        if !addresses.is_empty() {
            action.push_str(&format!(" :addresses {}", list(addresses)));
        }
        if !reply.subject.is_empty() {
            action.push_str(&format!(" :subject {}", string(&reply.subject)));
        }
        body.push_str(&format!(
            "if allof ({}) {{\r\n  {action}\r\n    {};\r\n}}\r\n",
            tests.join(&format!(",\r\n{INDENT}")),
            string(&reply.text)
        ));
    }
    if let Some(rules) = rules {
        body.push_str(&rules.text);
    }
    // Their script runs after the reply, so a `stop` in it can't keep the
    // reply from going out, and isn't an error if they delete it.
    if let Some(beside) = beside {
        body.push_str(&format!(
            "include :personal :optional {};\r\n",
            string(beside)
        ));
    }
    format!("{HEADER}\r\n{CHECK}{FORMAT} {}\r\n{body}", check(&body))
}

/// Reads the app's script `text`.
pub(crate) fn read(text: &str) -> Found {
    let beside = includes(text).into_iter().find(|name| name != NAME);
    let checked = text
        .strip_prefix(HEADER)
        .and_then(|rest| rest.strip_prefix("\r\n"))
        .and_then(|rest| rest.strip_prefix(CHECK))
        .and_then(|rest| rest.split_once("\r\n"))
        .and_then(|(line, body)| line.split_once(' ').map(|(_, value)| (value, body)));
    let edited = !checked.is_some_and(|(value, body)| value == check(body));
    let data = text
        .split("\r\n")
        .find_map(|line| line.strip_prefix(DATA))
        .and_then(|json| serde_json::from_str::<Data>(json).ok())
        .unwrap_or_default();
    let rules = data.rules.and_then(|rules| {
        let start = line(text, RULES_START)?;
        let end = start + line(&text[start..], RULES_END)?;
        let end = end + text[end..].find('\n')? + 1;
        Some(Section {
            text: text[start..end].to_owned(),
            needs: rules.needs,
            digest: rules.digest,
        })
    });
    Found {
        reply: AutoReply {
            enabled: data.enabled,
            subject: data.subject,
            text: data.text,
            starts_at: data.starts_at,
            ends_at: data.ends_at,
            contacts_only: false,
            domain_only: false,
        },
        rules,
        beside,
        edited,
    }
}

/// Where the line that is `wanted` starts in `text`, outside the strings,
/// where a reply's text or a rule's could hold such a line.
fn line(text: &str, wanted: &str) -> Option<usize> {
    let mut quoted = false;
    let mut at = 0;
    for line in text.split_inclusive('\n') {
        if !quoted && line.trim_end_matches(['\r', '\n']) == wanted {
            return Some(at);
        }
        let mut chars = line.chars();
        while let Some(c) = chars.next() {
            match (quoted, c) {
                (true, '\\') => {
                    chars.next();
                }
                (true, '"') => quoted = false,
                // The rest of the line is a comment.
                (false, '#') => break,
                (false, '"') => quoted = true,
                _ => {}
            }
        }
        at += line.len();
    }
    None
}

fn check(body: &str) -> String {
    Sha256::digest(body.as_bytes())[..8]
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

/// The zone offset and the day `at` falls on here, such as "+0100" and
/// "2026-11-16".
fn day(at: i64) -> Option<(String, String)> {
    let local = Local.timestamp_millis_opt(at).single()?;
    let seconds = local.offset().fix().local_minus_utc();
    let sign = if seconds < 0 { '-' } else { '+' };
    let minutes = seconds.unsigned_abs() / 60;
    Some((
        format!("{sign}{:02}{:02}", minutes / 60, minutes % 60),
        local.format("%Y-%m-%d").to_string(),
    ))
}

/// `text` as a Sieve quoted string (RFC 5228 section 2.4.2). Line breaks
/// become CRLF, as a lone CR or a NUL can't be in a script.
pub(super) fn string(text: &str) -> String {
    let text = text
        .replace("\r\n", "\n")
        .replace(['\r', '\n'], "\r\n")
        .replace('\0', "");
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

pub(super) fn list(items: &[impl AsRef<str>]) -> String {
    let items = items
        .iter()
        .map(|item| string(item.as_ref()))
        .collect::<Vec<_>>();
    format!("[{}]", items.join(", "))
}

/// The extensions a script requires.
pub(crate) fn requires(text: &str) -> Vec<String> {
    let tokens = tokens(text);
    let mut required = Vec::new();
    let mut tokens = tokens.iter();
    while let Some(token) = tokens.next() {
        if matches!(token, Token::Word(word) if word.eq_ignore_ascii_case("require")) {
            for token in tokens.by_ref() {
                match token {
                    Token::Text(extension) => required.push(extension.to_ascii_lowercase()),
                    Token::Other(';') => break,
                    _ => {}
                }
            }
        }
    }
    required
}

/// The user's scripts a script runs with `include` (RFC 6609), leaving out
/// global ones.
pub(crate) fn includes(text: &str) -> Vec<String> {
    let tokens = tokens(text);
    let mut included = Vec::new();
    let mut tokens = tokens.iter();
    while let Some(token) = tokens.next() {
        if matches!(token, Token::Word(word) if word.eq_ignore_ascii_case("include")) {
            let mut global = false;
            for token in tokens.by_ref() {
                match token {
                    Token::Word(tag) if tag.eq_ignore_ascii_case(":global") => global = true,
                    Token::Text(name) => {
                        if !global {
                            included.push(name.clone());
                        }
                        break;
                    }
                    Token::Other(_) => break,
                    Token::Word(_) => {}
                }
            }
        }
    }
    included
}

/// A unit of a script, comments left out (RFC 5228 section 8.1).
#[derive(Debug, PartialEq, Eq)]
enum Token {
    /// An identifier, a tag such as `:personal`, or a number.
    Word(String),
    /// A quoted or multi-line string.
    Text(String),
    Other(char),
}

fn tokens(text: &str) -> Vec<Token> {
    let mut tokens = Vec::new();
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '#' => {
                for c in chars.by_ref() {
                    if c == '\n' {
                        break;
                    }
                }
            }
            '/' if chars.peek() == Some(&'*') => {
                chars.next();
                let mut last = ' ';
                for c in chars.by_ref() {
                    if last == '*' && c == '/' {
                        break;
                    }
                    last = c;
                }
            }
            '"' => {
                let mut string = String::new();
                while let Some(c) = chars.next() {
                    match c {
                        '"' => break,
                        '\\' => string.extend(chars.next()),
                        c => string.push(c),
                    }
                }
                tokens.push(Token::Text(string));
            }
            c if c.is_ascii_alphanumeric() || c == '_' || c == ':' => {
                let mut word = String::from(c);
                while let Some(&c) = chars.peek() {
                    if !(c.is_ascii_alphanumeric() || c == '_') {
                        break;
                    }
                    word.push(c);
                    chars.next();
                }
                if word.eq_ignore_ascii_case("text") && chars.peek() == Some(&':') {
                    tokens.push(Token::Text(multi_line(&mut chars)));
                } else {
                    tokens.push(Token::Word(word));
                }
            }
            c if c.is_whitespace() => {}
            c => tokens.push(Token::Other(c)),
        }
    }
    tokens
}

/// The rest of a `text:` string: the lines up to one that is a lone dot,
/// with a leading dot removed from the others.
fn multi_line(chars: &mut std::iter::Peekable<std::str::Chars<'_>>) -> String {
    // The colon and the rest of its line, which may hold a comment.
    for c in chars.by_ref() {
        if c == '\n' {
            break;
        }
    }
    let mut string = String::new();
    loop {
        let mut line = String::new();
        let mut ended = false;
        for c in chars.by_ref() {
            if c == '\n' {
                ended = true;
                break;
            }
            line.push(c);
        }
        let line = line.strip_suffix('\r').unwrap_or(&line);
        if line == "." || !ended {
            return string;
        }
        string.push_str(line.strip_prefix('.').unwrap_or(line));
        string.push('\n');
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn away() -> AutoReply {
        AutoReply {
            enabled: true,
            subject: "Out of \"office\"".into(),
            text: "Away\nBack on Monday \\o/".into(),
            starts_at: Some(1_794_787_200_000),
            ends_at: Some(1_795_219_199_999),
            contacts_only: false,
            domain_only: false,
        }
    }

    #[test]
    fn a_reply_becomes_a_vacation_action_for_its_days_and_addresses() {
        let script = generate(
            &away(),
            &["me@example.test".into(), "alias@example.test".into()],
            None,
            None,
        );
        assert!(script.starts_with(&format!("{HEADER}\r\n{CHECK}{FORMAT} ")));
        assert!(script.contains("require [\"vacation\", \"date\", \"relational\"];"));
        let (_, first) = day(1_794_787_200_000).unwrap();
        let (_, last) = day(1_795_219_199_999).unwrap();
        assert!(script.contains(&format!(":value \"ge\" \"date\" \"{first}\"")));
        assert!(script.contains(&format!(":value \"le\" \"date\" \"{last}\"")));
        assert!(script.contains(
            "vacation :days 4 :addresses [\"me@example.test\", \"alias@example.test\"] :subject \"Out of \\\"office\\\"\"\r\n    \"Away\r\nBack on Monday \\\\o/\";"
        ));
        assert!(script.contains("header :contains \"X-Spam-Flag\" \"YES\""));
        assert!(!script.contains("include"));
        // Lines end in CRLF only.
        assert!(!script.replace("\r\n", "").contains('\n'));
    }

    #[test]
    fn the_rules_part_reads_back_as_written_whatever_the_reply_says() {
        let rules = Section {
            text: "# Rules\r\n# Rule: A\r\nif true {\r\n  stop;\r\n}\r\n# End of rules\r\n".into(),
            needs: vec!["fileinto".into()],
            digest: "d1".into(),
        };
        let tricky = AutoReply {
            text: "Away\n# Rules\n# End of rules\nBack \"soon\"".into(),
            ..away()
        };
        let script = generate(&tricky, &[], Some(&rules), Some("filters"));
        assert!(script.contains("# End of rules\r\ninclude :personal :optional \"filters\";"));
        let found = read(&script);
        assert_eq!(found.rules, Some(rules));
        assert_eq!(found.reply, tricky);
        assert_eq!(found.beside.as_deref(), Some("filters"));
        assert!(!found.edited);
        // Without data for the rules, there are none.
        assert_eq!(read(&generate(&tricky, &[], None, None)).rules, None);
    }

    #[test]
    fn line_breaks_become_crlf_and_nul_goes() {
        assert_eq!(string("a\rb\nc\r\nd\0e"), "\"a\r\nb\r\nc\r\nde\"");
    }

    #[test]
    fn the_script_reads_back_as_written() {
        let script = generate(&away(), &[], None, Some("roundcube"));
        assert_eq!(
            read(&script),
            Found {
                reply: away(),
                rules: None,
                beside: Some("roundcube".into()),
                edited: false,
            }
        );
        // A change anywhere below the check line shows.
        let changed = script.replace("Back on Monday", "Back on Tuesday");
        assert!(read(&changed).edited);
        assert!(read("keep;").edited);
        assert_eq!(read("keep;").reply, AutoReply::default());
    }

    #[test]
    fn replies_turned_off_keep_their_text_and_the_users_script() {
        let off = AutoReply {
            enabled: false,
            ..away()
        };
        assert_eq!(needs(&off, None), Vec::<&str>::new());
        let script = generate(&off, &[], None, None);
        assert!(!script.contains("require"));
        assert!(!script.contains("vacation :days"));
        assert_eq!(read(&script).reply, off);
        // Their script still runs.
        let beside = generate(&off, &[], None, Some("filters"));
        assert!(beside.contains("require [\"include\"];"));
        assert!(beside.ends_with("include :personal :optional \"filters\";\r\n"));
    }

    #[test]
    fn replies_without_days_need_no_dates() {
        let always = AutoReply {
            enabled: true,
            text: "Away".into(),
            ..AutoReply::default()
        };
        assert_eq!(needs(&always, None), ["vacation"]);
        let script = generate(&always, &[], None, None);
        assert!(script.contains("require [\"vacation\"];"));
        assert!(!script.contains("currentdate"));
        assert!(script.contains("vacation :days 4\r\n    \"Away\";"));
    }

    #[test]
    fn requires_and_includes_skip_comments_and_strings() {
        let script = "require [\"fileinto\", \"Vacation\"]; # require \"enotify\";\r\n\
                      /* include \"hidden\"; */\r\n\
                      require \"include\";\r\n\
                      if header :is \"Subject\" text: # a comment\r\n\
                      include \"in a string\";\r\n\
                      ..dot-stuffed\r\n\
                      .\r\n\
                      { include :personal :once \"filters\"; }\r\n\
                      include :global \"spam\";\r\n\
                      include \"quoted \\\"name\\\"\";\r\n";
        assert_eq!(requires(script), ["fileinto", "vacation", "include"]);
        assert_eq!(includes(script), ["filters", "quoted \"name\""]);
    }
}
