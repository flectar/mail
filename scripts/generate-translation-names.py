#!/usr/bin/env python3
"""Write src/translation/names_data.rs: languages named in each language the app is in, from CLDR.

The reader says what language a message is in, and Settings lists the languages to translate
into, in the app's own language. The names are CLDR's, as written in a sentence; menus
capitalize them. The app's languages are English and the catalogs in lang/.
"""

import json
from pathlib import Path
import sys
import urllib.error
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/translation/names_data.rs"
CLDR = "https://raw.githubusercontent.com/unicode-org/cldr-json/48.0.0/cldr-json"

# The variants translation services offer that a name needs: English and Portuguese for DeepL,
# Chinese scripts for DeepL and LibreTranslate, and DeepL's regional Spanish, French and German.
VARIANTS = ["en-GB", "en-US", "pt-BR", "pt-PT", "zh-Hans", "zh-Hant", "es-419", "fr-CA", "de-CH"]


def fetch(path):
    request = urllib.request.Request(
        f"{CLDR}/{path}", headers={"User-Agent": "flectar-mail-ci (+https://github.com/flectar/mail)"}
    )
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return None
        raise


def rust_string(value):
    return json.dumps(value, ensure_ascii=False)


def app_languages():
    """The app's languages as CLDR locales, with the code the app uses for each."""
    codes = ["en"] + sorted(path.name for path in (ROOT / "lang").iterdir() if path.is_dir())
    return [(code, code.replace("_", "-")) for code in codes]


def main():
    english = fetch("cldr-localenames-full/main/en/languages.json")
    english = english["main"]["en"]["localeDisplayNames"]["languages"]
    # Every language with a two-letter code, which is every language a translation service
    # names, and the variants above. CLDR keys variants with "_" in its JSON.
    wanted = sorted(code for code in english if len(code) == 2) + VARIANTS
    lines = [
        "// Languages named in each language the app is in, from CLDR 48, as written in a",
        "// sentence. Generated by scripts/generate-translation-names.py; change the script and",
        "// run it again.",
        "",
        "/// The app's language, then each language tag and its name in it.",
        "pub(super) const NAMES: &[(&str, &[(&str, &str)])] = &[",
    ]
    for code, locale in app_languages():
        names = fetch(f"cldr-localenames-full/main/{locale}/languages.json")
        if names is None:
            print(f"no CLDR names for {locale}", file=sys.stderr)
            continue
        names = names["main"][locale]["localeDisplayNames"]["languages"]
        lines.append(f'    ("{code}", &[')
        for tag in wanted:
            name = names.get(tag) or names.get(tag.replace("-", "_"))
            if name is None:
                continue
            lines.append(f'        ("{tag}", {rust_string(name)}),')
        lines.append("    ]),")
    lines.append("];")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
